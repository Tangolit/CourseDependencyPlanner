from typing import Protocol


class CourseRepository(Protocol):
    def get_data(self) -> dict: ...
    def save_data(self, data: dict, force: bool = False) -> tuple[dict, list[str]]: ...
    def import_data(self, data: dict, force: bool = False) -> tuple[dict, list[str]]: ...
    def undo(self) -> dict | None: ...
